import { describe, expect, it, vi } from 'vitest';
import { saveSessionTemplate } from './saveSessionTemplate';
import type { WorkoutExercise } from '../../types';

const exercise = (fields = {}): WorkoutExercise => ({
  id: 'row-1', category_id: 'plan', exercise_id: 'new-exercise',
  exercise_name: 'Remada', sets: 2, reps: '12', weight: 25, rest_time: 75, order: 0,
  sets_json: [{ reps: '12', weight: 25, rest_time: 75, rpe: 8 },
    { reps: '10', weight: 30, rest_time: 90, rpe: 9 }] as any,
  ...fields,
});

function database(initial: any[] = []) {
  let rows = structuredClone(initial);
  const state = { historyCategory: 'plan', noAck: false, corruptRead: false, failWrite: false };
  const writes = vi.fn();
  const client = { from(table: string) {
    let action = 'select', payload: any, single = false;
    const filters: ((row: any) => boolean)[] = [];
    const query: any = {
      select: () => query,
      eq: (key: string, value: any) => { filters.push(row => row[key] === value); return query; },
      in: (key: string, values: any[]) => { filters.push(row => values.includes(row[key])); return query; },
      single: () => { single = true; return query; },
      upsert: (values: any[]) => { action = 'upsert'; payload = values; return query; },
      delete: () => { action = 'delete'; return query; },
      then(resolve: any, reject: any) {
        let result: any;
        if (table === 'workout_categories') result = { data: { id: 'plan' }, error: null };
        else if (table === 'workout_history') result = { data: { category_id: state.historyCategory }, error: null };
        else if (action === 'upsert') {
          writes(payload);
          if (state.failWrite) result = { error: new Error('offline') };
          else {
            for (const row of payload) rows = [...rows.filter(item => item.id !== row.id), structuredClone(row)];
            result = { data: state.noAck ? [] : payload.map((row: any) => ({ id: row.id })), error: null };
          }
        } else if (action === 'delete') {
          rows = rows.filter(row => !filters.every(filter => filter(row)));
          result = { data: null, error: null };
        } else {
          let selected = rows.filter(row => filters.every(filter => filter(row)));
          if (state.corruptRead && writes.mock.calls.length) selected = selected.map(row => ({ ...row, exercise_id: 'wrong' }));
          result = { data: single ? selected[0] : structuredClone(selected), error: null };
        }
        return Promise.resolve(result).then(resolve, reject);
      },
    };
    return query;
  } };
  return { client: client as any, state, writes, rows: () => rows };
}

async function save(db: ReturnType<typeof database>, exercises = [exercise()], removedIds: string[] = []) {
  return saveSessionTemplate(db.client, { workoutId: 'plan', userId: 'user', historyId: 'session', exercises, removedIds });
}

describe('confirmed session template saves', () => {
  it('persists a replacement against live rows without relying on an original snapshot', async () => {
    const db = database([{ id: 'row-1', category_id: 'plan', exercise_id: 'old-exercise' }]);
    await save(db);
    expect(db.rows()[0]).toMatchObject({ exercise_id: 'new-exercise', exercise_name_snapshot: 'Remada', sort_order: 0 });
    expect(db.rows()[0].sets_json[1]).toMatchObject({ reps: '10', weight: 30, rest_time: 90 });
  });
  it('recreates a missing row in an empty ficha, and retries without duplicates', async () => {
    const db = database();
    await save(db);
    await save(db); // Original stale row ID is still in local recovery storage.
    expect(db.rows()).toHaveLength(1);
    expect(db.rows()[0].exercise_id).toBe('new-exercise');
  });
  it('reconciles IDs regenerated by the editor without inserting a duplicate', async () => {
    const db = database([{ id: 'regenerated', category_id: 'plan', exercise_id: 'new-exercise' }]);
    const saved = await save(db);
    expect(saved[0].id).toBe('regenerated');
    expect(db.rows()).toHaveLength(1);
  });
  it('refuses an ambiguous stale replacement rather than overwriting a different row', async () => {
    const db = database([{ id: 'different', category_id: 'plan', exercise_id: 'other-exercise' }]);
    await expect(save(db)).rejects.toThrow('A ficha mudou');
    expect(db.writes).not.toHaveBeenCalled();
  });
  it('rejects a session linked to a different ficha before writing', async () => {
    const db = database();
    db.state.historyCategory = 'other-plan';
    await expect(save(db)).rejects.toThrow('outra ficha');
    expect(db.writes).not.toHaveBeenCalled();
  });
  it('rejects exercise rows from another ficha before writing', async () => {
    const db = database();
    await expect(save(db, [exercise({ category_id: 'other-plan' })])).rejects.toThrow('outra ficha');
    expect(db.writes).not.toHaveBeenCalled();
  });
  it('does not report success for a zero-row write or failed reread', async () => {
    const db = database();
    db.state.noAck = true;
    await expect(save(db)).rejects.toThrow('não confirmou');
    const badRead = database();
    badRead.state.corruptRead = true;
    await expect(save(badRead)).rejects.toThrow('não confirmou');
  });
  it('propagates write failure and preserves existing rows', async () => {
    const db = database([{ id: 'row-1', category_id: 'plan', exercise_id: 'old' }]);
    db.state.failWrite = true;
    await expect(save(db)).rejects.toThrow('offline');
    expect(db.rows()[0].exercise_id).toBe('old');
  });
  it('retries a newly added exercise without duplicating it', async () => {
    const db = database();
    const added = exercise({ id: 'ex-live-new' });
    await save(db, [added]);
    await save(db, [added]);
    expect(db.rows()).toHaveLength(1);
  });
  it('deletes only explicitly removed rows, scoped to the target ficha', async () => {
    const db = database([
      { id: 'row-1', category_id: 'plan', exercise_id: 'old' },
      { id: 'removed', category_id: 'plan', exercise_id: 'remove' },
      { id: 'preserved', category_id: 'plan', exercise_id: 'keep' },
      { id: 'foreign', category_id: 'other-plan', exercise_id: 'foreign' },
    ]);
    await save(db, [exercise()], ['removed', 'foreign']);
    expect(db.rows().map(row => row.id)).toEqual(expect.arrayContaining(['row-1', 'preserved', 'foreign']));
    expect(db.rows().some(row => row.id === 'removed')).toBe(false);
  });
});
